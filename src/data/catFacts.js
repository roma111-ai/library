export function getRandomCatFact(excludeIndexes = []) {
  // Исключаем уже использованные — чтобы факты не повторялись
  const available = CAT_FACTS.map((_, i) => i).filter(i => !excludeIndexes.includes(i));
  if (available.length === 0) return null;
  const idx = available[Math.floor(Math.random() * available.length)];
  return { index: idx, text: CAT_FACTS[idx] };
}